"""Generate browser API bindings with the same wasm-bindgen version as Cargo.lock."""
import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parent.parent
CODEC_BINDGEN_VERSION = '0.2.128'


def _replace_generated_function(code, name, replacement):
    matches = list(re.finditer(r'^function ' + re.escape(name) + r'\([^\n]*\) \{', code, re.MULTILINE))
    if len(matches) != 1:
        raise RuntimeError(f'Expected one generated {name} helper, got {len(matches)}')
    start = matches[0].start()
    position = matches[0].end()
    depth = 1
    # These pinned wasm-bindgen helpers contain only ordinary JS statements;
    # assert the supported shape before replacing their complete function body.
    while depth and position < len(code):
        depth += (code[position] == '{') - (code[position] == '}')
        position += 1
    if depth:
        raise RuntimeError(f'Unterminated generated {name} helper')
    return code[:start] + replacement + code[position:]


def rust_string_bindings(code, version):
    """Keep JS String ABI transfer thin; UTF-8/UTF-16 conversion runs in Rust.

    The raw Vec export transfers one boxed allocation to the normal Rust String
    ABI receiver. Decode borrows the existing allocation and never frees it.
    Fixed generator version and shapes prevent silently applying an ABI rewrite
    to a different wasm-bindgen implementation.
    """
    if version != CODEC_BINDGEN_VERSION:
        raise RuntimeError(f'Rust string bindings require wasm-bindgen {CODEC_BINDGEN_VERSION}, got {version}')
    for signature in ('export function browser_encode_utf8(', 'export function browser_decode_utf8('):
        if code.count(signature) != 1:
            raise RuntimeError(f'Missing Rust codec export: {signature}')
    if 'return decodeText(ptr >>> 0, len);' not in code or 'const ret = cachedTextEncoder.encodeInto(arg, view);' not in code:
        raise RuntimeError('Unexpected generated String ABI shape')
    code = _replace_generated_function(code, 'getStringFromWasm0', '''function getStringFromWasm0(ptr, len) {
    return wasm.browser_decode_utf8(ptr >>> 0, len);
}''')
    code = _replace_generated_function(code, 'passStringToWasm0', '''function passStringToWasm0(arg, _malloc, _realloc) {
    const ret = wasm.browser_encode_utf8(arg);
    WASM_VECTOR_LEN = ret[1];
    return ret[0];
}''')
    code, count = re.subn(r"let cachedTextDecoder = new TextDecoder\('utf-8', \{ ignoreBOM: true, fatal: true \}\);.*?\nlet WASM_VECTOR_LEN = 0;", 'let WASM_VECTOR_LEN = 0;', code, flags=re.DOTALL)
    if count != 1 or re.search(r'TextEncoder|TextDecoder|cachedTextEncoder|cachedTextDecoder|\bdecodeText\b|MAX_SAFARI_DECODE_BYTES|numBytesDecoded', code):
        raise RuntimeError('Generated JavaScript still contains a string codec')
    return code


def bindgen_executable():
    lock = tomllib.loads((ROOT / 'rust/Cargo.lock').read_text(encoding='utf-8'))
    version = next(package['version'] for package in lock['package'] if package['name'] == 'wasm-bindgen')
    executable = os.environ.get('ROGUE_WASM_BINDGEN') or shutil.which('wasm-bindgen')
    if not executable:
        candidates = sorted((ROOT / '.local/tools/wasm-bindgen').glob('wasm-bindgen-*/wasm-bindgen.exe'))
        executable = str(candidates[-1]) if candidates else None
    if not executable:
        raise RuntimeError(f'Install wasm-bindgen-cli {version} or set ROGUE_WASM_BINDGEN to its executable')
    actual = subprocess.check_output([executable, '--version'], text=True).strip()
    if actual != f'wasm-bindgen {version}':
        raise RuntimeError(f'Expected wasm-bindgen {version}, got {actual}')
    return executable, version


def bind_browser(source, output, name='browser-ui'):
    if name not in ('browser-ui', 'browser-test'):
        raise ValueError('Unsupported browser artifact name')
    executable, version = bindgen_executable()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run([executable, str(source), '--target', 'web', '--no-typescript', '--out-dir', str(output), '--out-name', name], check=True)
    # Keep the public artifact filename stable across both compiler entry points.
    generated = output / (name + '.js')
    code = generated.read_text(encoding='utf-8').replace(name + '_bg.wasm', name + '.wasm')
    code = rust_string_bindings(code, version)
    generated.write_text(f'// Generated by wasm-bindgen {version} from rogue-browser-display.\n' + code, encoding='utf-8', newline='\n')
    (output / (name + '_bg.wasm')).replace(output / (name + '.wasm'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, nargs='?')
    parser.add_argument('output', type=Path, nargs='?')
    parser.add_argument('--print-executable', action='store_true')
    parser.add_argument('--name', choices=('browser-ui', 'browser-test'), default='browser-ui')
    arguments = parser.parse_args()
    if arguments.print_executable:
        print(bindgen_executable()[0])
    elif arguments.source is None or arguments.output is None:
        parser.error('source and output are required')
    else:
        bind_browser(arguments.source, arguments.output, arguments.name)
